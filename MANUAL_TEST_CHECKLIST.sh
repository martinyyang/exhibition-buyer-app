echo "========================================"
echo -e "${YELLOW}Common Issues to Watch For:${NC}"
echo "  - RLS policy errors (403/401 from Supabase)"
echo "  - Infinite recursion errors"
echo "  - Missing environment variables"
echo "  - CORS errors"
echo "  - Base href issues (404s for assets)"
echo "  - Chinese text displaying as boxes"
echo ""

echo "========================================"
echo -e "${YELLOW}After Testing:${NC}"
echo "  1. Document any issues found"
echo "  2. Check LOCAL_E2E_STATUS.md for agent results"
